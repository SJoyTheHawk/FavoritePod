"""Render local previews from the canonical Elementor fragments (Python 3)."""

import os
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
SITE = HERE.parent / "site" / "favoritepod"
PAGES = [
    ("overview", "index.html", "FavoritePod — Rocky Road Studio",
     "Save websites and local tools in one visual home. FavoritePod offers folders, "
     "previews, backups, and optional Google Drive sync."),
    ("privacy", "privacy/index.html", "FavoritePod Privacy Policy — Rocky Road Studio",
     "How FavoritePod handles bookmarks, previews, local files, optional Google "
     "Drive sync, support requests, and data deletion."),
    ("support", "support/index.html", "FavoritePod Support — Rocky Road Studio",
     "Get help with FavoritePod, saving pages, local file access, Google Drive sync, "
     "backups, and privacy questions."),
]

for name, destination, title, description in PAGES:
    output = SITE / destination
    output.parent.mkdir(parents=True, exist_ok=True)

    def relative(path):
        return Path(os.path.relpath(path, output.parent)).as_posix()

    content = (HERE / "pages" / f"{name}.html").read_text(encoding="utf-8")
    content = content.replace(
        "{{FAVORITEPOD_ICON_URL}}", relative(SITE / "assets" / "favoritepod-icon.png")
    ).replace(
        "{{FAVORITEPOD_SCREENSHOT_URL}}",
        relative(SITE / "assets" / "favoritepod-visual-home.png"),
    )

    def rewrite_link(match):
        route = match.group(1) or ""
        anchor = match.group(2) or ""
        return f'href="{relative(SITE / route / "index.html")}{anchor}"'

    content = re.sub(
        r'href="/favoritepod/(privacy/|support/)?(#[^"]+)?"', rewrite_link, content
    )
    content = re.sub(r"<!--.*?-->\s*", "", content, count=1, flags=re.DOTALL)
    page = f'''<!doctype html>
<!-- Generated by wordpress/build_previews.py. Edit wordpress/pages/ instead. -->
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <meta name="robots" content="noindex" />
    <meta name="description" content="{description}" />
    <title>{title}</title>
    <link rel="icon" href="{relative(SITE / 'assets/favoritepod-icon.png')}" type="image/png" />
    <link rel="stylesheet" href="{relative(SITE / 'preview.css')}" />
    <link rel="stylesheet" href="{relative(HERE / 'favoritepod.css')}" />
  </head>
  <body class="fp-preview">
    <a class="fp-preview-skip" href="#main">Skip to content</a>
    <div class="fp-preview-note">Local content preview. WordPress supplies the real studio header and footer.</div>
    <header class="fp-preview-header">
      <a class="fp-preview-brand" href="https://rockyroad.studio/">Rocky Road Studio</a>
      <nav aria-label="Studio navigation">
        <a href="https://rockyroad.studio/">Home</a>
        <a href="https://rockyroad.studio/blog/">Blog</a>
        <a href="https://rockyroad.studio/photo/">Photo Story</a>
      </nav>
    </header>
    <main id="main">
{content.rstrip()}
    </main>
    <footer class="fp-preview-footer">
      <div>
        <p><strong>Rocky Road Studio</strong></p>
        <p>Preview framing only; keep the existing WordPress footer.</p>
      </div>
      <nav aria-label="Studio information">
        <a href="https://rockyroad.studio/privacy-policy/">Website privacy</a>
        <a href="https://rockyroad.studio/declaration-of-ai-use/">AI use</a>
        <a href="mailto:rockyroadstudio@outlook.com">Contact</a>
      </nav>
    </footer>
  </body>
</html>
'''
    output.write_text(page, encoding="utf-8")
    print(f"Rendered {output.relative_to(HERE.parent)}")
